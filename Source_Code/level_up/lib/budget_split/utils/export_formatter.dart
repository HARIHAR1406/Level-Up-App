// =============================================================================
// BudgetSplit - Export Formatter
// =============================================================================
// Formats budget breakdown as ASCII plaintext for sharing via messaging apps.
// =============================================================================

import '../models/budget_category.dart';
import 'budget_calculator.dart';

/// Formatter that generates the exact plain text tabular export format
/// specified in the BudgetSplit technical specification.
class ExportFormatter {
  ExportFormatter._();

  static const String separatorLine = '────────────────────────────────────────────'; // 44 chars

  /// Formats the budget plan into a monospace plain text block
  static String formatPlan({
    required String planName,
    required double totalBudget,
    required List<BudgetCategory> categories,
  }) {
    final effectivePlanName =
        planName.trim().isEmpty ? 'Untitled Plan' : planName.trim();
    final buffer = StringBuffer();

    // Header
    buffer.writeln('BudgetSplit — $effectivePlanName');
    buffer.writeln(separatorLine);
    buffer.writeln('Total Budget : ${BudgetCalculator.formatAmountOnly(totalBudget)}');
    buffer.writeln();

    // Table Header
    buffer.writeln('${'Categories'.padRight(20)}${'Percentage'.padRight(12)}Amount');
    buffer.writeln(separatorLine);

    // Categories
    double totalPct = 0.0;
    double totalAllocAmt = 0.0;

    for (final cat in categories) {
      final pctVal = cat.percentageValue;
      if (pctVal <= 0) continue; // Skip zero/empty categories in summary as per spec

      final amt = BudgetCalculator.calculateCategoryAmount(totalBudget, pctVal);
      totalPct += pctVal;
      totalAllocAmt += amt;

      final catName = cat.displayName.length > 18
          ? '${cat.displayName.substring(0, 17)}…'
          : cat.displayName;
      final pctStr = BudgetCalculator.formatPercentage(pctVal);
      final amtStr = BudgetCalculator.formatAmountOnly(amt);

      buffer.writeln('${catName.padRight(20)}${pctStr.padRight(12)}$amtStr');
    }

    // Total row
    buffer.writeln(separatorLine);
    final totalPctStr = BudgetCalculator.formatPercentage(totalPct);
    final totalAmtStr = BudgetCalculator.formatAmountOnly(totalAllocAmt);
    buffer.writeln('${'Total'.padRight(20)}${totalPctStr.padRight(12)}$totalAmtStr');
    buffer.writeln();
    buffer.writeln('Generated by BudgetSplit');

    return buffer.toString();
  }
}
